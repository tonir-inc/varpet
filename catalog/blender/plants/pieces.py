def _cactus_texture(ribs):
    rng = np.random.default_rng(13)
    H, W = 512, 128  # one rib wide, 0.1 m tall
    u = np.linspace(0, 1, W)[None, :].repeat(H, 0)
    v = np.linspace(0, 1, H)[:, None].repeat(W, 1)
    crest = np.abs(u - 0.5) * 2  # 1 at the crest (u=0/1), 0 in the groove
    n = P.fbm(H, W, 16, 4, rng, 3, wrap_x=True)
    base = P.rgb("#4f7d5c") * (0.62 + 0.3 * crest[..., None] + 0.12 * n[..., None])
    col = base.copy()
    hgt = crest * 0.5
    for k in range(4):
        cy = (k + 0.5) / 4
        for cx in (0.0, 1.0):
            d = np.sqrt(((u - cx) * 1.0) ** 2 + ((v - cy) * 0.25) ** 2)
            dot = np.clip(1 - d / 0.07, 0, 1)
            col = col * (1 - dot[..., None]) + P.rgb("#d8d2bf") * dot[..., None]
            # radiating spines
            ang = np.arctan2((v - cy) * 0.25, (u - cx))
            rr = d
            sp = (np.abs(np.sin(ang * 5)) < 0.08) & (rr < 0.28) & (rr > 0.05)
            col[sp] = P.rgb("#e9e1c8")
            hgt = hgt + dot * 0.6
    return P.image("cactus", col), P.image("cactus-n", P.normal_from_height(hgt, 2.0), color=False)


def _ribbed(B, pts, radius, ribs=7, depth=0.28, v_rep=10.0, per_rib=8):
    """Columnar cactus stem: tube with deep rounded ribs, domed tip. UV repeats once per rib."""
    fr = P.frames(pts)
    sides = ribs * per_rib
    rows, uvs, acc = [], [], 0.0
    L = sum((b - a).length for a, b in zip(pts, pts[1:]))
    for i, (p, (t, n, b)) in enumerate(zip(pts, fr)):
        if i:
            acc += (p - pts[i - 1]).length
        tt = acc / L
        r = radius(tt)
        ring, ruv = [], []
        for k in range(sides + 1):
            a = TAU * k / sides
            prof = 1 - depth * (1 - abs(math.cos(ribs * a / 2))) ** 1.4
            ring.append(p + r * prof * (math.cos(a) * n + math.sin(a) * b))
            ruv.append((k / per_rib, acc * v_rep))
        rows.append(ring)
        uvs.append(ruv)
    B.grid(rows, uvs, flip=True)


