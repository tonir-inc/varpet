def _monstera_alpha(S, T, k):
    at = np.abs(T) * 2
    a = np.ones_like(S)
    a[(S < 0.13) & (at < 0.3 * (1 - S / 0.13))] = 0  # cordate notch
    n = 8 if k == 0 else 6
    phase = (S - 0.2 * at ** 1.1) * n + 0.5
    d = np.abs(phase - np.round(phase))
    inner = 0.3 if k == 0 else 0.55
    wedge = 0.03 + 0.06 * np.clip((at - inner) / (1 - inner), 0, 1)
    band = (S > 0.14) & (S < 0.9)
    a[(d < wedge) & (at > inner) & band] = 0
    if k == 0:
        hole = ((at - 0.17) / 0.055) ** 2 + (d / 0.07) ** 2 < 1
        a[hole & band & (S < 0.8)] = 0
    return a


