def _feather_alpha(S, T, k):
    """Fine diverging fibres from the card base (u) spreading across (v): reads as fluff, not a feather."""
    rng = np.random.default_rng(90 + k)
    H, W = S.shape
    a = np.zeros((H, W))
    cols = np.arange(W)
    for _ in range(50):
        v0 = rng.uniform(0.4, 0.6)
        v1 = np.clip(v0 + (v0 - 0.5) * rng.uniform(1.0, 2.6) + rng.normal(0, 0.12), 0.02, 0.98)
        end = rng.uniform(0.55, 1.0)
        s = cols / (W - 1)
        m = s <= end
        curve = v0 + (v1 - v0) * (s ** 0.7) + 0.02 * np.sin(s * rng.uniform(4, 9) + rng.uniform(0, 6))
        rows = np.clip((curve * (H - 1)).astype(int), 0, H - 1)
        a[rows[m], cols[m]] = 1
    return a


