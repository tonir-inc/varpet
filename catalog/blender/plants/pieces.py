def _snake_paint(S, T, col, rng, k):
    n = P.fbm(S.shape[0], S.shape[1], 3, 24, rng, 3)
    phase = S * 34 + 0.35 * np.abs(np.sin(T * 30)) + 1.6 * n
    band = np.clip((np.sin(phase * TAU) - 0.25) / 0.5, 0, 1) * (0.55 + 0.45 * n)
    light = P.rgb("#8fa98a")
    at = np.abs(T) * 2
    band *= (at < 0.8)
    out = col * (1 - 0.65 * band[..., None]) + light * 0.65 * band[..., None]
    return out


