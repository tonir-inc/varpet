def interp(xs, ys):
    return lambda s: float(np.interp(s, xs, ys))


def azim(a, elev):
    """Unit vector at azimuth a (radians, 0 = +X) and elevation elev (radians)."""
    return Vector((math.cos(a) * math.cos(elev), math.sin(a) * math.cos(elev), math.sin(elev)))


def bark_mat(name, base, rough=0.85, fissure=0.5, seed=8):
    return mat(name, tex=P.texture_bark(name, base, seed, fissure), rough=rough)


def rad(d):
    return math.radians(d)


