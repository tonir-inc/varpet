PARADISE = interp([0, 0.04, 0.15, 0.4, 0.7, 0.86, 0.95, 1.0], [0.15, 0.55, 0.88, 1.0, 0.95, 0.72, 0.4, 0.04])


def _paradise_alpha(S, T, k):
    import random
    r = random.Random(50 + k)
    at = np.abs(T) * 2
    a = np.ones_like(S)
    for _ in range(r.randint(3, 6)):
        s0 = r.uniform(0.15, 0.9)
        sgn = r.choice((1, -1))
        depth = r.uniform(0.25, 0.8)
        w = r.uniform(0.002, 0.006)
        a[(np.abs(S - s0 - 0.04 * at) < w * (0.4 + at)) & (np.sign(T) == sgn) & (at > 1 - depth)] = 0
    return a


