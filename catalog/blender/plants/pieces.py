def olive_tree():
    rng = P.rng_for("olive")
    soil_z, _ = pot("terracotta", 0.19, 0.3, r_bot=0.14, seed=21)
    col, nrm = P.leaf_texture("olive", [dict(base="#4a5a34", vein="#5d6b45", mid="#8a9570"),
                                        dict(base="#7d8a6c", vein="#909c80", mid="#a8b196")],
                              W=256, TH=64, n_veins=1, vein_amt=0.0, mid_w=0.06, mid_amt=0.5, mottle=0.08, seed=3)
    L, W = Builder(), Builder()
    stats = {"leaves": 0}

    def branch(p0, d, length, r0, depth):
        n = 4
        ctrl = [p0]
        dd = d.normalized()
        for i in range(n):
            dd = (dd + Vector((rng.uniform(-0.35, 0.35), rng.uniform(-0.35, 0.35), rng.uniform(-0.1, 0.25)))).normalized()
            ctrl.append(ctrl[-1] + dd * length / n)
        pts = catmull(ctrl, 3 if depth else 2)
        tube(W, pts, lambda t: r0 * (1 - 0.6 * t), sides=7 if depth >= 3 else (5 if depth == 2 else 3), jitter=0.25 if depth >= 2 else 0, rng=rng)
        if depth == 0:
            m = 8
            for i in range(m):
                t = 0.2 + 0.8 * i / m
                p, tan = P.point_on(pts, t)
                side = tan.cross(Vector((0, 0, 1)))
                if side.length < 1e-3:
                    side = Vector((1, 0, 0))
                side.normalize()
                rot = Matrix.Rotation(i * 1.4, 3, tan)
                for sgn in (1, -1):
                    dirv = (tan * 0.75 + (rot @ side) * sgn * 0.65 + Vector((0, 0, -0.1))).normalized()
                    ln = rng.uniform(0.05, 0.07)
                    P.strip_leaf(L, p, dirv, ln, ln * 0.18, nu=4, bend=rng.uniform(0.1, 0.5), fold=0.3,
                                 variant=1 if rng.random() < 0.3 else 0, nvar=2, twist=rng.uniform(-0.8, 0.8))
                    stats["leaves"] += 1
            P.strip_leaf(L, pts[-1], tan, 0.055, 0.01, nu=4, bend=0.2, variant=0, nvar=2)
            return
        kids = {3: 3, 2: 3, 1: 3}[depth]
        for c in range(kids):
            t = 0.45 + 0.55 * (c + 1) / kids
            p, tan = P.point_on(pts, min(t, 0.98))
            a = math.atan2(tan.y, tan.x) + rng.uniform(-1.3, 1.3) + (c % 2 - 0.5) * 1.2
            elev = rng.uniform(0.3, 0.95)
            branch(p, azim(a, elev), length * rng.uniform(0.5, 0.7), r0 * 0.6, depth - 1)

    # two leaning intertwined trunks, then a loose crown
    t1 = catmull([(0, 0, soil_z - 0.03), (0.03, 0.01, 0.45), (-0.02, 0.03, 0.62), (0.02, 0.0, 0.76)], 5)
    t2 = catmull([(0.02, -0.02, soil_z - 0.03), (-0.03, -0.02, 0.46), (0.01, -0.03, 0.6), (-0.03, -0.01, 0.7)], 5)
    tube(W, t1, lambda t: 0.028 - 0.01 * t, sides=10, jitter=0.35, rng=rng)
    tube(W, t2, lambda t: 0.022 - 0.008 * t, sides=10, jitter=0.35, rng=rng)
    for i, (tp, a) in enumerate(((t1, 0.3), (t1, 2.4), (t2, 4.2), (t2, 5.5), (t1, 1.3))):
        p = tp[-1] if i < 4 else P.point_on(tp, 0.8)[0]
        branch(p, azim(a, rng.uniform(0.55, 0.9)), rng.uniform(0.3, 0.38), 0.014, 3)
    W.obj("wood", bark_mat("olive-bark", "#8a8578", 0.9, 0.55))
    L.obj("leaves", mat("olive-leaf", tex=col, normal=nrm, nstrength=0.3, rough=0.55))


