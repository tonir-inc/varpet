    St.obj("stems", sz.plain("sz-euca-stem", "#6d4b3d", 0.8))
    L.obj("leaves", mat("sz-euca-leaf", tex=col, normal=nrm, nstrength=0.4, rough=0.7))
    # linen bow at the gather and the loop at the top of the hoop
    Bw = Builder()
    g = Vector((R * math.cos(gather), -0.03, zc + R * math.sin(gather)))
    for sg in (1, -1):
        loop = [g + Vector((sg * 0.035 * math.sin(math.pi * k / 10), -0.004 * math.sin(math.pi * k / 10),
                            0.018 * math.sin(2 * math.pi * k / 10))) for k in range(11)]
        tube(Bw, loop, 0.0045, sides=6, cap_end=False)
        tail = [g, g + Vector((sg * 0.02, -0.004, -0.05)), g + Vector((sg * 0.03, -0.002, -0.1))]
        tube(Bw, sz.catmull(tail, 4), 0.0045, sides=6)
    sz.sphere(Bw, g, 0.008, 8, 5)
    top = Vector((0, 0, zc + R))
    tab = [top + Vector((0.01 * math.sin(TAU * k / 12), 0.0, 0.03 * (1 - math.cos(TAU * k / 12)))) for k in range(13)]
    tube(Bw, tab, 0.003, sides=6, cap_end=False)
    Bw.obj("linen", sz.plain("sz-linen", "#d8cebd", 0.9))


