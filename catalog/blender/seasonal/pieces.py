def fir_tree(slug, height, basket_r, basket_h, tint, n_baubles, n_lights, radius, dressed=True, pot="basket",
             variants=None, whorl_dz=0.1, step=0.05, bauble_r=(0.032, 0.05), stars=6, top_r=0.075, per_whorl=(6, 8)):
    rng = sz.rng_for(slug)
    soil_z, _ = pp.pot(pot, basket_r, basket_h, r_bot=basket_r * 0.84, seed=31, tint=tint)
    C, W = Builder(), Builder()
    base = soil_z - 0.01
    tr = sz.conifer(C, W, base + 0.1 * height, height * 0.9, radius, rng, whorl_dz=whorl_dz, step=step,
                    per_whorl=per_whorl, trunk_r=0.03 * min(1, height / 1.5) + 0.004,
                    card_len=0.14 * min(1, height / 1.5) + 0.03, card_w=0.1 * min(1, height / 1.5) + 0.018)
    tube(W, [Vector((0, 0, base)), Vector((0, 0, base + 0.1 * height + 0.02))], 0.028 * height / 1.8 + 0.01, sides=8)
    W.obj("wood", pp.mat("sz-bark", tex=pp.texture_bark("sz-bark", "#5c4a3a", 4, 0.4), rough=0.9))
    C.obj("needles", sz.needle_mat("sz-fir", variants))
    if dressed:
        dress(tr, rng, n_baubles, bauble_r[0], bauble_r[1], base, n_lights, stars=stars)
        topper(tr.top, top_r)
    return tr


