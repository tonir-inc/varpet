# ================================================================ tulips in glass vase
PETAL = lambda s: math.sin(math.pi * min(1.0, 0.1 + s * 0.92)) ** 0.5 * (0.85 + 0.15 * s)


def tulip_vase():
    rng = sz.rng_for("tulips")
    V = Builder()
    prof = [(0.0, 0.0), (0.05, 0.0), (0.056, 0.004), (0.056, 0.23), (0.052, 0.232), (0.051, 0.23),
            (0.051, 0.016), (0.0, 0.016)]
    pp.lathe(V, prof, steps=48)
    V.obj("vase", sz.kit.material("glass")[0])
    Wt = Builder()
    pp.lathe(Wt, [(0.0, 0.016), (0.05, 0.016), (0.05, 0.14), (0.0, 0.14)], steps=36)
    Wt.obj("water", sz.kit.material("glass")[0])
    ptex, pnrm = pp.leaf_texture("sz-petal", [dict(base="#f2c6cc", vein="#e7aeb7", mid="#dc9ba6"),
                                              dict(base="#f4ece0", vein="#ecdcc8", mid="#e3cfb4")],
                                 W=256, TH=128, n_veins=14, vein_k=0.1, vein_amt=0.15, mid_amt=0.2, mottle=0.05,
                                 seed=51, nstrength=0.4)
    ltex, lnrm = pp.leaf_texture("sz-tulip-leaf", [dict(base="#6b8a5e", vein="#7c9a6e", mid="#8aa67b")],
                                 W=256, TH=64, n_veins=1, vein_amt=0.0, mid_amt=0.3, mottle=0.08, seed=52, nstrength=0.3)
    St, Pt, Lf = Builder(), Builder(), Builder()
    n = 9
    for i in range(n):
        a = i * GOLD
        spread = 0.04 + 0.1 * (i / n) ** 0.7
        base = Vector((0.018 * math.cos(a), 0.018 * math.sin(a), 0.02))
        lip = Vector((0.03 * math.cos(a), 0.03 * math.sin(a), 0.23))
        hz = rng.uniform(0.36, 0.44) - 0.04 * (i / n)
        head = Vector((spread * math.cos(a), spread * math.sin(a), hz))
        droop = Vector((0, 0, -0.02 * (i / n)))
        pts = sz.catmull([base, lip, (lip + head) / 2 + azim(a, 0) * 0.01, head + droop], 5)
        tube(St, pts, 0.0035, sides=6, cap_end=False)
        axis = (pts[-1] - pts[-3]).normalized()
        T = Builder()
        var = 0 if i % 3 else 1
        for k in range(6):
            pa = k * TAU / 6 + (0.5 if k % 2 else 0)
            rad_v = azim(pa, 0)
            ln = 0.052 if k % 2 == 0 else 0.048
            r0 = 0.004 if k % 2 == 0 else 0.007
            d = (UP + rad_v * 0.28).normalized()
            leaf(T, rad_v * r0, d, ln, 0.038, PETAL, nu=8, nv=5, bend=-0.45, cup=0.35, up=rad_v, variant=var, nvar=2,
                 thick=0.08)
        sz.merge(Pt, T, sz.frame_to(axis, pts[-1]))
        if i % 2 == 0:
            lb = Vector((0.03 * math.cos(a + 0.4), 0.03 * math.sin(a + 0.4), 0.2))
            leaf(Lf, lb, azim(a + 0.4, rad(62)), 0.2, 0.034, lambda s: math.sin(math.pi * min(1, 0.15 + s)) ** 0.5,
                 nu=10, nv=3, bend=1.1, fold=0.3, twist=0.5, variant=0, nvar=1)
    St.obj("stems", sz.plain("sz-tulip-stem", "#6f8e57", 0.5))
    Pt.obj("petals", mat("sz-petal", tex=ptex, normal=pnrm, nstrength=0.3, rough=0.45))
    Lf.obj("leaves", mat("sz-tulip-leaf", tex=ltex, normal=lnrm, nstrength=0.3, rough=0.5))


