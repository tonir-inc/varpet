def table_garland():
    rng = sz.rng_for("garland")
    L = 1.2
    path = lambda x: Vector((x, 0.035 * math.sin(x * 5.5), 0.0))
    sprigs, cones, berries = [], [], []
    x = -L / 2
    k = 0
    while x < L / 2 - 0.1:
        p = path(x) + Vector((0, rng.uniform(-0.04, 0.04), 0.012 + rng.uniform(0, 0.03)))
        dirx = 1 if k % 2 == 0 else -1
        start = p if dirx > 0 else p + Vector((0.18, 0, 0))
        d = Vector((dirx, rng.uniform(-0.45, 0.45), rng.uniform(0.02, 0.15)))
        sprigs.append((start, d, rng.uniform(0.18, 0.26)))
        x += 0.06
        k += 1
    for i in range(9):
        xx = -L / 2 + 0.08 + (L - 0.16) * i / 8 + rng.uniform(-0.03, 0.03)
        c = path(xx) + Vector((0, rng.uniform(-0.05, 0.05), 0.024))
        a = rng.uniform(0, TAU)
        cones.append((c - azim(a, 0) * 0.035, azim(a, rad(rng.uniform(5, 20))), rng.uniform(0.06, 0.08), 0.022))
    for i in range(14):
        xx = -L / 2 + 0.05 + (L - 0.1) * rng.random()
        c = path(xx) + Vector((0, rng.uniform(-0.06, 0.06), 0.06 + rng.uniform(-0.01, 0.02)))
        berries.append((c, 0.006))
    greenery(sprigs, cones, rng, berries)
    E, Wr = Builder(), Builder()
    wire = [path(-L / 2 + L * i / 60) + Vector((0, 0.03 * math.sin(i * 1.3), 0.055 + 0.015 * math.sin(i * 0.9)))
            for i in range(61)]
    tube(Wr, wire, 0.0012, sides=3, cap_end=False)
    for i in range(1, 60, 2):
        sz.octa(E, wire[i] + Vector((0, 0, 0.004)), 0.007)
    Wr.obj("wire", sz.plain("sz-wire", "#8a6a3c", 0.4, 1.0))
    E.obj("lights", sz.emit_mat("sz-fairy", WARM, 25.0))


