# ================================================================ shared bits
def wax():
    return sz.plain("sz-wax", "#f2ede3", 0.45)


def lit_candles(specs, kind="pillar"):
    """specs: [(x, y, z, r, h)]. Wax, wicks and flames."""
    Wx, Wk, E = Builder(), Builder(), Builder()
    for x, y, z, r, h in specs:
        (sz.pillar if kind == "pillar" else sz.taper)(Wx, Wk, E, (x, y, z), r, h)
    Wx.obj("wax", wax())
    Wk.obj("wick", sz.plain("sz-wick", "#1b1714", 0.8))
    E.obj("flame", sz.emit_mat("sz-flame", "#ffb45a", 18.0))


def greenery(sprigs, cones, rng, berries=(), card_len=0.11, card_w=0.07):
    """sprigs: [(p, d, length)], cones: [(at, axis, length, r)], berries: [(c, r)]."""
    C, W, K, Bb = Builder(), Builder(), Builder(), Builder()
    for p, d, ln in sprigs:
        sz.sprig(C, W, Vector(p), Vector(d), ln, rng, card_len=card_len, card_w=card_w, step=card_len * 0.42)
    for at, axis, ln, r in cones:
        sz.pine_cone(K, Vector(at), Vector(axis), ln, r, rng)
    for c, r in berries:
        sz.sphere(Bb, c, r, 8, 5)
    C.obj("needles", sz.needle_mat())
    W.obj("twigs", sz.plain("sz-twig", "#5a4631", 0.85))
    if K.P:
        K.obj("cones", mat("sz-cone", tex=sz.gradient_tex("sz-cone", "#3b2718", "#9a7650"), rough=0.85))
    if Bb.P:
        Bb.obj("berries", sz.plain("sz-berry", "#efece4", 0.4))


