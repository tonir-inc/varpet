def gift_box(size, at, rotz, paper, ribbon, bow=True, ribbon_w=0.022):
    kit = sz.kit
    before = set(kit.meshes())
    w, d, h = size
    kit.box(size, (0, 0, 0), paper, bevel=0.003)
    t = 0.0025
    kit.box((ribbon_w, d + 2 * t, h + t), (0, 0, 0), ribbon, bevel=0.0)
    kit.box((w + 2 * t, ribbon_w, h + t), (0, 0, 0), ribbon, bevel=0.0)
    if bow:
        Bw = Builder()
        c = Vector((0, 0, h + t))
        for k, ang in enumerate((0.5, 0.5 + math.pi, 1.9, 1.9 + math.pi)):
            ln = 0.055 if k < 2 else 0.042
            dirv = azim(ang, 0)
            loop = [c + dirv * ln * math.sin(math.pi * j / 12) * 1.0 + Vector((0, 0, 0.028 * math.sin(math.pi * j / 12) ** 0.6))
                    + dirv.cross(UP) * 0.012 * math.sin(2 * math.pi * j / 12) for j in range(13)]
            tube(Bw, loop, 0.0055, sides=6, cap_end=False)
        for ang in (0.9, 0.9 + math.pi + 0.5):
            tube(Bw, [c, c + azim(ang, 0) * 0.07 + Vector((0, 0, -0.002))], 0.005, sides=5)
        sz.sphere(Bw, c + Vector((0, 0, 0.006)), 0.011, 8, 5)
        m = sz.kit.material(ribbon)[0]
        Bw.obj("bow", m)
    import mathutils
    M = mathutils.Matrix.Translation(Vector(at)) @ mathutils.Matrix.Rotation(rad(rotz), 4, "Z")
    for o in set(kit.meshes()) - before:
        o.matrix_world = M @ o.matrix_world


